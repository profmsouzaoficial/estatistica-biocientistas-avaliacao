import { chromium } from 'playwright'
const WEB = 'http://127.0.0.1:3210'
const sufixo = String(Date.now()).slice(-6)
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 390, height: 900 }, locale: 'pt-BR' })
const p = await ctx.newPage()
p.setDefaultTimeout(30000)
p.on('response', async (r) => {
  if (r.url().includes('/api/turma-excluir')) console.log('API turma-excluir:', r.status(), (await r.text()).slice(0, 200))
})
// professor cria turma
await p.goto(`${WEB}/entrar`, { waitUntil: 'networkidle' })
await p.getByLabel('E-mail').fill('marcio.souza@ufjf.br')
await p.getByLabel('Senha').fill(process.env.SENHA_PROFESSOR)
await p.getByRole('button', { name: 'Entrar' }).click()
await p.waitForURL((u) => !u.pathname.startsWith('/entrar'))
await p.goto(`${WEB}/prof/alunos`, { waitUntil: 'networkidle' })
await p.getByRole('button', { name: 'Nova turma' }).click()
const codigo = 'FOTOS' + sufixo
await p.getByLabel('Nome da turma').fill('Turma foto ' + sufixo)
await p.getByLabel('Código no SIGA').fill(codigo)
await p.getByRole('button', { name: 'Criar turma' }).click()
await p.getByText('Turma criada').waitFor()
const sel = p.getByLabel('Turma').first()
const valor = await sel.locator('option', { hasText: codigo }).first().getAttribute('value')
await sel.selectOption(valor)
const caixa = p.getByRole('checkbox', { name: /Exigir o e-mail/ })
if (await caixa.isChecked()) { await caixa.uncheck(); await p.getByText('Agora a lista pode vir só').waitFor() }
await p.locator('textarea').fill(`9999${sufixo};Aluno Foto`)
await p.getByRole('button', { name: 'Conferir e importar' }).click()
await p.getByText(/incluíd/).first().waitFor()
// avaliação publicada
await p.goto(`${WEB}/prof/avaliacoes/nova`, { waitUntil: 'networkidle' })
await (async () => {
  const sel = (await p.getByLabel('Turma').count()) ? p.getByLabel('Turma').first() : p.locator('select').first()
  await sel.selectOption(valor)
})()
await p.getByLabel('Título').fill('Avaliação foto ' + sufixo)
await p.locator('#tema').fill('Tema de teste para foto.')
await p.locator('#instrucoes').fill('Escreva pouco.')
await p.getByLabel('Valor total (pontos)').fill('10')
await p.getByRole('button', { name: /Distribuir 10 pts/ }).click()
await p.getByRole('button', { name: 'Publicar avaliação' }).click()
await p.waitForURL(/\/prof\/avaliacoes\/[0-9a-f-]{36}/)
// aluno se cadastra e envia com foto
const pagAluno = await ctx.newPage()
await pagAluno.goto(`${WEB}/cadastrar`, { waitUntil: 'networkidle' })
await pagAluno.getByLabel('Turma').selectOption(valor)
await pagAluno.getByLabel('Nome completo').fill('Aluno Foto')
await pagAluno.getByLabel('Matrícula', { exact: true }).fill(`9999${sufixo}`)
await pagAluno.getByLabel('E-mail').fill(`foto.${sufixo}@estudante.ufjf.br`)
await pagAluno.getByLabel('Senha', { exact: true }).fill('Teste12345')
await pagAluno.getByRole('button', { name: /Criar conta|Cadastrar/ }).click()
await pagAluno.waitForURL((u) => !u.pathname.startsWith('/cadastrar'), { timeout: 30000 })
await pagAluno.getByRole('link', { name: /Avaliação foto/ }).first().click()
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==', 'base64')
await pagAluno.locator('input[type=file]').first().setInputFiles({ name: 'foto.png', mimeType: 'image/png', buffer: png })
await pagAluno.getByRole('button', { name: /Usar esta foto/ }).click()
await pagAluno.getByText(/transcrição automática ainda não está configurada/).waitFor({ timeout: 20000 })
await pagAluno.getByLabel('Texto da sua redação').fill('Texto de teste para validar a limpeza da foto. '.repeat(5))
const c = pagAluno.getByRole('checkbox').last()
if (!(await c.isChecked())) await c.check()
await pagAluno.getByRole('button', { name: 'Enviar redação' }).click()
await pagAluno.getByText('Redação enviada').waitFor({ timeout: 20000 })
// professor remove a turma
await p.goto(`${WEB}/prof/alunos`, { waitUntil: 'networkidle' })
const selectAvaliacao = (await p.getByLabel('Turma').count()) ? p.getByLabel('Turma').first() : p.locator('select').first()
await selectAvaliacao.selectOption(valor)
await p.getByRole('button', { name: /Remover esta turma/ }).click()
await p.getByText('Isto não pode ser desfeito').waitFor()
await p.getByLabel(`Digite ${codigo} para confirmar`).fill(codigo)
const botao = p.getByRole('button', { name: /Remover turma definitivamente/ })
await botao.waitFor()
console.log('botão habilitado?', await botao.isEnabled())
await botao.click()
await p.getByText(/Turma .* removida/).waitFor({ timeout: 30000 })
console.log('mensagem:', await p.getByText(/Turma .* removida/).innerText())
await b.close()
